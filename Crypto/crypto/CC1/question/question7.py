
def rsa_chiffrement(m, e, n):
    """
    m : entier message < n
    e : exposant public
    n : module
    renvoie le cryptogramme c
    """
    return pow(m, e, n)

# Calcul de l'inverse de a modulo p
def inverse(a, p):
    orig = p
    u, v = 1, 0
    u1, v1 = 0, 1
    while p != 0:
        q = a // p

        u, u1 = u1, u - q * u1
        v, v1 = v1, v - q * v1

        a, p = p, a % p

    return u % orig



